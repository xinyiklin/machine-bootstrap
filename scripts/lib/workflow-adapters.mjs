// Generates provider-native agent definitions from the provider-neutral role
// contracts. The Markdown contracts are the source of truth; nothing here adds
// behavior that is not in them, and no model is pinned so each provider keeps
// its own default.
//
// Generation is deterministic: same contracts in, byte-identical adapters out.
// No timestamps, no host paths, no environment values.

import { readFileSync } from "node:fs";
import { join } from "node:path";

export const GENERATOR = "machine-bootstrap";

// Both providers read the whole body as instructions, so line endings are
// normalized and a trailing newline is guaranteed. That keeps a CRLF checkout
// from producing different adapters than an LF one.
function normalizeContract(path) {
  const contract = readFileSync(path, "utf8")
    .replaceAll("\r\n", "\n")
    .replaceAll("\r", "\n");
  if (!contract.trim()) {
    throw new Error(`Role contract is empty: ${path}`);
  }
  return contract.endsWith("\n") ? contract : `${contract}\n`;
}

function provenanceLines(pkg, role) {
  return [
    `Generated by ${GENERATOR}; do not edit here.`,
    `workflow: ${pkg.manifest.workflowId} ${pkg.manifest.workflowVersion} ` +
    `(schema ${pkg.manifest.schemaVersion})`,
    `role: ${role.id}`,
    `source: workflows/${pkg.manifest.workflowId}/${role.source}`,
    "Edit the canonical role contract, then rerun " +
    "scripts/install-workflows.mjs."
  ];
}

// A YAML double-quoted scalar keeps a summary containing ":" or "#" valid.
function yamlQuoted(value) {
  return `"${value.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`;
}

// JSON string encoding is a deterministic subset of TOML basic-string
// encoding: quotes, backslashes, control characters, and line endings are all
// escaped, while Unicode remains readable. This also avoids delimiter hazards
// when complete Markdown contracts contain either kind of quote triple.
function tomlQuoted(value) {
  // JSON escapes C0 controls but leaves DEL literal; TOML forbids DEL in a
  // basic string, so encode that final control explicitly.
  return JSON.stringify(value).replaceAll("\u007f", "\\u007F");
}

export function generateClaudeAgent(pkg, role) {
  const contract = normalizeContract(join(pkg.root, role.source));
  const provenance = provenanceLines(pkg, role)
    .map((line) => `     ${line}`)
    .join("\n")
    .trimStart();

  return (
    "---\n" +
    `name: ${role.claude.name}\n` +
    `description: ${yamlQuoted(role.summary)}\n` +
    "---\n" +
    "\n" +
    `<!-- ${provenance} -->\n` +
    "\n" +
    contract
  );
}

export function generateCodexAgent(pkg, role) {
  const contract = normalizeContract(join(pkg.root, role.source));
  const provenance = provenanceLines(pkg, role)
    .map((line) => `# ${line}`)
    .join("\n");

  return (
    `${provenance}\n` +
    "\n" +
    `name = ${tomlQuoted(role.codex.name)}\n` +
    `description = ${tomlQuoted(role.summary)}\n` +
    `developer_instructions = ${tomlQuoted(contract)}\n`
  );
}

export function generateCodexProfile(pkg, role) {
  const contract = normalizeContract(join(pkg.root, role.source));
  const provenance = [
    ...provenanceLines(pkg, role),
    `Launch: codex --profile ${role.codex.profile}`
  ]
    .map((line) => `# ${line}`)
    .join("\n");

  return (
    `${provenance}\n` +
    "\n" +
    `developer_instructions = ${tomlQuoted(contract)}\n`
  );
}

// Returns every provider file this workflow owns, as path segments relative to
// that provider's configuration root plus the exact bytes to install. Nothing
// outside these paths is bootstrap-owned.
export function generateProviderAdapters(pkg) {
  const adapters = [];

  for (const role of pkg.manifest.roles) {
    adapters.push({
      provider: "claude",
      kind: "agent",
      roleId: role.id,
      segments: ["agents", `${role.claude.name}.md`],
      contents: generateClaudeAgent(pkg, role)
    });
    adapters.push({
      provider: "codex",
      kind: "agent",
      roleId: role.id,
      segments: ["agents", `${role.codex.name}.toml`],
      contents: generateCodexAgent(pkg, role)
    });
    if (role.codex.profile) {
      adapters.push({
        provider: "codex",
        kind: "profile",
        roleId: role.id,
        segments: [`${role.codex.profile}.config.toml`],
        contents: generateCodexProfile(pkg, role)
      });
    }
  }

  return adapters;
}
